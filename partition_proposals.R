# Shared partition prior and local Metropolis-Hastings proposal.

# 1. Log Stirling numbers --------

# Compute log(exp(a) + exp(b)) without exponentiating the larger term.
log_add_exp <- function(a, b) {
  hi <- max(a, b)
  if (is.infinite(hi)) return(hi)
  hi + log1p(exp(min(a, b) - hi))
}

# Stirling numbers of the second kind count unlabeled partitions.
# Use the recurrence S(i, j) = j * S(i - 1, j) + S(i - 1, j - 1).
log_stirling2 <- function(n, k) {
  if (k < 0 || k > n) return(-Inf)
  if (n == 0 && k == 0) return(0)
  if (k == 0) return(-Inf)
  if (k == 1 || k == n) return(0)
  if (k == 2) {
    x <- (n - 1) * log(2)
    return(x + log1p(-exp(-x)))
  }

  previous <- c(0, rep(-Inf, k))
  for (i in seq_len(n)) {
    current <- rep(-Inf, k + 1L)
    for (j in seq_len(min(i, k))) {
      current[j + 1L] <- log_add_exp(
        log(j) + previous[j + 1L], previous[j]
      )
    }
    previous <- current
  }
  previous[k + 1L]
}

# 2. Partition prior --------

# Log prior for one particular partition with l blocks. The normalizer
# counts all S(p, l) partitions of each intermediate size.
log_partition_prior <- function(l, pro, p) {
  if (p == 1L) return(0)
  if (l == 1L) return(log(pro) - log1p(pro))

  log_normalizer <- 0
  for (j in seq_len(p - 2L) + 1L) {
    log_weight <- log(pro) + (p - j - 1L) * log1p(pro)
    log_normalizer <- log_add_exp(
      log_normalizer, log_weight + log_stirling2(p, j)
    )
  }
  log_prior <- -log1p(pro) - log_normalizer
  if (l < p) log_prior <- log_prior + log(pro) + (p - l - 1L) * log1p(pro)
  log_prior
}

# 3. Local partition proposal --------

# Label blocks in order of first appearance.
canonicalize_partition <- function(s) {
  match(s, unique(s))
}

partition_blocks <- function(s) {
  split(seq_along(s), s)
}

# Boundary moves include a self-transition, as in the size proposal.
partition_size_moves <- function(l, p) {
  seq.int(max(-1L, 1L - l), min(1L, p - l))
}

size_move_prob <- function(lnew, lold, p) {
  moves <- partition_size_moves(lold, p)
  if ((lnew - lold) %in% moves) 1 / length(moves) else 0
}

# Generate a partition conditional on the chosen change in block count.
propose_local_partition <- function(s, move) {
  s <- canonicalize_partition(s)
  blocks <- partition_blocks(s)
  l <- length(blocks)
  if (!move %in% partition_size_moves(l, length(s))) {
    stop("The move is unavailable for this partition size.")
  }

  splittable <- which(lengths(blocks) >= 2L)
  if (move == 0L) {
    if (l == 1L || l == length(s)) return(s)

    movable <- unlist(blocks[splittable], use.names = FALSE)
    treatment <- movable[sample.int(length(movable), 1L)]
    destinations <- setdiff(seq_len(l), s[treatment])
    s[treatment] <- destinations[sample.int(length(destinations), 1L)]
  } else if (move == 1L) {
    block <- splittable[sample.int(length(splittable), 1L)]
    remaining <- blocks[[block]][-1L]

    # Fix the first member in the first block, and reject empty second blocks.
    # The remaining assignments give each unordered two-block split equal mass.
    repeat {
      second <- as.logical(sample.int(2L, length(remaining), replace = TRUE) - 1L)
      if (any(second)) break
    }
    s[remaining[second]] <- l + 1L
  } else {
    pair <- sample.int(l, 2L)
    s[s == pair[2L]] <- pair[1L]
  }
  canonicalize_partition(s)
}

# 4. Proposal probabilities --------

# Count how many treatment moves yield the same unlabeled partition.
# Either member of a two-treatment block can sometimes yield the same result.
within_move_log_prob <- function(from, to) {
  blocks <- partition_blocks(from)
  l <- length(blocks)
  if (l == 1L || l == length(from)) return(if (identical(from, to)) 0 else -Inf)

  movable <- unlist(blocks[lengths(blocks) >= 2L], use.names = FALSE)
  ways <- 0L
  for (j in movable) {
    # Once j is removed, the two block assignments must agree up to relabeling.
    if (!identical(canonicalize_partition(from[-j]), canonicalize_partition(to[-j]))) next
    partners <- which(to == to[j] & seq_along(to) != j)
    if (length(partners) && from[partners[1L]] != from[j]) ways <- ways + 1L
  }
  log(ways) - log(length(movable)) - log(l - 1L)
}

# Conditional proposal probabilities for a candidate generated by the kernel.
# The separate size-move probabilities also enter the acceptance ratio.
proposal_log_probs <- function(s_old, s_new, move) {
  s_old <- canonicalize_partition(s_old)
  s_new <- canonicalize_partition(s_new)
  l_old <- length(unique(s_old))
  l_new <- length(unique(s_new))
  if (!move %in% c(-1L, 0L, 1L) || l_new - l_old != move) {
    stop("The partitions do not match the requested move.")
  }

  if (move == 0L) {
    log_q_forward <- within_move_log_prob(s_old, s_new)
    log_q_reverse <- within_move_log_prob(s_new, s_old)
  } else {
    coarse <- if (move == 1L) s_old else s_new
    fine <- if (move == 1L) s_new else s_old
    blocks <- partition_blocks(coarse)
    split_block <- vapply(blocks, function(b) length(unique(fine[b])), integer(1L)) == 2L
    if (sum(split_block) != 1L) stop("Expected one split block.")

    log_split <- -log(sum(lengths(blocks) >= 2L)) -
      log_stirling2(lengths(blocks)[split_block], 2L)
    log_merge <- -lchoose(length(unique(fine)), 2L)
    log_q_forward <- if (move == 1L) log_split else log_merge
    log_q_reverse <- if (move == 1L) log_merge else log_split
  }

  list(
    log_q_forward = log_q_forward,
    log_q_reverse = log_q_reverse,
    log_hastings = log_q_reverse - log_q_forward,
    q_forward = exp(log_q_forward),
    q_reverse = exp(log_q_reverse)
  )
}

# 5. Partition likelihoods --------

# Evaluate a treatment partition conditional on the supplied mixture allocations.
univariate_partition_log_likelihood <- function(y, ci, labels, k0, a0, b0, mu0) {
  total <- 0
  for (label in unique(ci)) {
    for (block in unique(labels)) {
      yi <- y[ci == label & labels == block]
      count <- length(yi)
      if (count == 0L) next
      center <- mean(yi)
      precision <- k0 + count
      shape <- a0 + count / 2
      rate <- b0 + 0.5 * sum((yi - center)^2) +
        (k0 * count * (center - mu0)^2) / (2 * precision)

      total <- total + gsl::lngamma(shape) - gsl::lngamma(a0) +
        a0 * log(b0) - shape * log(rate) +
        0.5 * (log(k0) - log(precision)) - 0.5 * count * log(2 * pi)
    }
  }
  total
}

# Evaluate a treatment partition conditional on the supplied mixture allocations.
multivariate_partition_log_likelihood <- function(y, ci, labels, k0, a0, Psi0, mu0, m) {
  total <- 0
  for (label in unique(ci)) {
    for (block in unique(labels)) {
      yi <- y[ci == label & labels == block, , drop = FALSE]
      count <- nrow(yi)
      if (count == 0L) next
      center <- colMeans(yi)
      precision <- k0 + count
      df <- a0 + count
      scatter <- crossprod(sweep(yi, 2L, center))
      scale_matrix <- Psi0 + scatter +
        (k0 * count / precision) * tcrossprod(center - mu0)

      total <- total + CholWishart::lmvgamma(df / 2, m) - CholWishart::lmvgamma(a0 / 2, m) +
        0.5 * (a0 * log(det(Psi0)) - df * log(det(scale_matrix))) +
        0.5 * m * (log(k0) - log(precision)) - 0.5 * count * m * log(pi)
    }
  }
  total
}

# 6. Density plot helpers --------

# Label treatments by their block in the most probable sampled partition.
# For tied posterior probabilities, use the first partition in the table.
posterior_density_groups <- function(postprob) {
  model <- names(postprob)[which.max(postprob)]
  blocks <- strsplit(model, ",", fixed = TRUE)[[1L]]
  treatments <- split(seq_along(blocks), blocks)
  labels <- vapply(treatments, function(j) {
    prefix <- if (length(j) == 1L) "Treatment" else "Treatments"
    paste(prefix, paste(j, collapse = ", "))
  }, character(1L))
  factor(labels[blocks], levels = unname(labels[unique(blocks)]))
}

# Return the pointwise 25th and 75th percentiles as columns.
density_quartiles <- function(draws) {
  t(apply(draws, 2L, stats::quantile, probs = c(0.25, 0.75)))
}

# Convert a density matrix to long form in grid order for the contour plot.
contour_grid_data <- function(xgrid, ygrid, density, treatment, type) {
  grid <- expand.grid(x = xgrid, y = ygrid)
  grid$z <- as.vector(density)
  grid$comp <- treatment
  grid$type <- type
  grid
}
